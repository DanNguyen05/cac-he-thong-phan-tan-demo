import { expect, test } from '@playwright/test'
import type { Page, APIRequestContext } from '@playwright/test'
const titles = { rpc: '8.3 Reliable Client–Server', group: '8.4 Reliable Group Communication', commit: '8.5 Distributed Commit', recovery: '8.6 Recovery' }
async function navigate(page: Page, module: keyof typeof titles) {
  await page.locator(`button[title="${titles[module]}"]`).click()
  await expect(page.locator('#scenario')).toBeVisible()
}
async function done(request: APIRequestContext, status = 'COMPLETED') {
  await expect.poll(async () => (await (await request.get('/api/state')).json()).run?.status, { timeout: 25000 }).toBe(status)
  return (await (await request.get('/api/state')).json())
}
async function settings(page: Page) { await page.getByRole('button', { name: 'Cài đặt', exact: true }).click() }
async function close(page: Page) { await page.getByRole('button', { name: 'Đóng', exact: true }).click() }
