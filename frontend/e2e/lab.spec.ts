test('keyboard shortcuts work after button clicks and preserve text input', async ({ page, request }) => {
  await navigate(page, 'rpc')
  await page.getByRole('button', { name: 'Từng bước', exact: true }).click()
  await page.getByRole('button', { name: /^Trình chiếu/ }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: /^Trình chiếu/ })).toBeVisible()
  await page.getByRole('button', { name: /^Trình chiếu/ }).click()
  await page.getByRole('button', { name: 'Chạy thí nghiệm', exact: true }).click()
  await done(request, 'WAITING')
  await expect(page.getByRole('button', { name: /^Bước tiếp/ })).toBeEnabled()
  await page.keyboard.press('n'); await done(request)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: /^Trình chiếu/ })).toBeVisible()
  await page.getByRole('button', { name: 'Xem tất cả', exact: true }).click()
  const search = page.getByPlaceholder('Tìm sự kiện, message ID, node...')
  await search.focus(); await page.keyboard.press('p')
  await expect(search).toHaveValue('p')
  await expect(page.locator('.app')).not.toHaveClass(/presentation/)
  await close(page); await settings(page)
  await page.getByRole('button', { name: 'Hướng dẫn nhanh' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
