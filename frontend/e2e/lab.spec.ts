test('presentation step mode gates recovery and survives node crash', async ({ page, request }) => {
  await navigate(page, 'recovery'); await page.locator('#scenario').selectOption('idempotent')
  await page.getByRole('button', { name: 'Từng bước', exact: true }).click()
  await page.getByRole('button', { name: /^Trình chiếu/ }).click()
  await page.getByRole('button', { name: 'Chạy thí nghiệm', exact: true }).click()
  await done(request, 'WAITING')
  expect((await (await request.get('/api/state')).json()).nodes.A.memory_value).toBe(0)
  for (let step = 0; step < 12; step++) {
    const state = await (await request.get('/api/state')).json()
    if (state.run.status === 'COMPLETED') break
    await expect(page.getByRole('button', { name: /^Bước tiếp/ })).toBeEnabled()
    await page.getByRole('button', { name: /^Bước tiếp/ }).click()
    await expect.poll(async () => {
      const next = await (await request.get('/api/state')).json()
      return next.run.status === 'COMPLETED' || (next.run.status === 'WAITING' && next.events.length > state.events.length)
    }).toBeTruthy()
  }
  const recovered = await done(request)
  expect(recovered.nodes.A.memory_value).toBe(20)
  expect(recovered.run.result.before_pid).not.toBe(recovered.run.result.after_pid)
  await expect(page.getByRole('button', { name: /Thoát trình chiếu/ })).toBeVisible()
  await page.screenshot({ path: '../test-results/reference-presentation.png', fullPage: true })
})
