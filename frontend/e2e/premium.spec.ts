import { expect, test } from '@playwright/test'
test.beforeEach(async ({ request }) => { expect((await request.post('/api/reset')).ok()).toBeTruthy() })
async function settings(page: import('@playwright/test').Page) { await page.getByRole('button', { name: 'Cài đặt', exact: true }).click() }
async function close(page: import('@playwright/test').Page) { await page.getByRole('button', { name: 'Đóng', exact: true }).click() }

test('all workspaces fit five viewport widths and support deep links', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  for (const width of [375, 768, 1024, 1440, 1920]) {
    await page.setViewportSize({ width, height: 1080 })
    for (const route of ['/', '/rpc', '/group', '/commit', '/recovery']) {
      await page.goto(route)
      await expect(page.getByTestId('connection')).toHaveAttribute('data-connected', 'true')
      await expect(page.locator('[data-renderer]')).toBeVisible()
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (route === '/commit') await page.screenshot({ path: `../test-results/reference-commit-${width}.png`, fullPage: true })
    }
  }
  await page.goto('/rpc'); await page.reload()
  await expect(page.locator('#scenario')).toBeVisible()
  expect(errors).toEqual([])
})

test('React Flow supports zoom, drag, inspect and SVG fallback', async ({ page }) => {
  await page.goto('/commit')
  const node = page.locator('.topology-page:not([hidden]) .react-flow__node[data-id="A"]')
  await expect(node).toBeVisible()
  const before = await node.boundingBox()
  expect(before).not.toBeNull()
  await page.mouse.move(before!.x + 50, before!.y + 70); await page.mouse.down()
  await page.mouse.move(before!.x + 90, before!.y + 90, { steps: 8 }); await page.mouse.up()
  const after = await node.boundingBox()
  expect(Math.abs(after!.x - before!.x)).toBeGreaterThan(15)
  const viewport = page.locator('.topology-page:not([hidden]) .react-flow__viewport'), transform = await viewport.getAttribute('style')
  await page.getByRole('button', { name: 'Zoom In', exact: true }).click()
  await expect.poll(() => viewport.getAttribute('style')).not.toBe(transform)
  await node.click()
  await expect(page.getByRole('dialog')).toContainText('PROCESS ID')
  await close(page); await settings(page)
  await page.getByRole('combobox', { name: 'Bộ hiển thị' }).selectOption('svg')
  await close(page)
  await expect(page.locator('[data-renderer="svg"]')).toBeVisible()
  await page.getByRole('button', { name: 'Kiểm tra Node B' }).click()
  await expect(page.getByRole('dialog')).toContainText('Node B')
  await close(page)
  await page.getByRole('button', { name: 'Căn vừa sơ đồ' }).click()
  await page.screenshot({ path: '../test-results/reference-svg.png', fullPage: true })
})

test('P pauses real execution, N advances while paused, inputs remain editable', async ({ page, request }) => {
  await page.goto('/recovery'); await page.locator('#scenario').selectOption('idempotent')
  await page.getByRole('button', { name: '0.5×', exact: true }).click()
  await page.getByRole('button', { name: 'Chạy thí nghiệm', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Tạm dừng', exact: true })).toBeEnabled()
  await page.keyboard.press('p')
  await expect(page.getByRole('button', { name: 'Tiếp tục', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: /^Bước tiếp/ })).toBeEnabled()
  const paused = (await (await request.get('/api/state')).json()).nodes.A.memory_value
  await page.getByRole('button', { name: 'Xem tất cả', exact: true }).click()
  const search = page.getByRole('textbox', { name: 'Tìm kiếm sự kiện' })
  await search.focus(); await page.keyboard.type('np')
  await expect(search).toHaveValue('np')
  expect((await (await request.get('/api/state')).json()).nodes.A.memory_value).toBe(paused)
  await close(page)
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).focus(); await page.keyboard.press('n')
  await expect.poll(async () => (await (await request.get('/api/state')).json()).nodes.A.memory_value).not.toBe(paused)
  await expect(page.getByRole('button', { name: /^Bước tiếp/ })).toBeEnabled()
  await page.getByRole('button', { name: '2×', exact: true }).click()
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
  await expect.poll(async () => (await (await request.get('/api/state')).json()).run.status, { timeout: 20000 }).toBe('COMPLETED')
  await expect(page.getByTestId('metric-Đã replay')).toHaveText('2')
  await settings(page); await page.getByText('Trạng thái & nguyên lý', { exact: true }).click()
  await expect(page.locator('.operation-log .replayed')).toHaveCount(2)
  await close(page)
  await page.screenshot({ path: '../test-results/reference-recovery.png', fullPage: true })
})

test('2PC blocking is explicit and sequence messages match the journal', async ({ page, request }) => {
  await page.goto('/commit'); await page.locator('#scenario').selectOption('coordinator_crash')
  await page.getByRole('button', { name: '2×', exact: true }).click()
  await page.getByRole('button', { name: 'Chạy thí nghiệm', exact: true }).click()
  await expect.poll(async () => (await (await request.get('/api/state')).json()).run.status, { timeout: 20000 }).toBe('BLOCKED')
  await expect(page.locator('.topology-page:not([hidden]) .service-node.server-node .node-status')).toHaveText(['PREPARED', 'PREPARED', 'PREPARED'])
  await expect(page.locator('.protocol-phases')).toContainText('BLOCKED')
  const state = await (await request.get('/api/state')).json()
  await page.getByRole('button', { name: 'Xem sơ đồ trình tự' }).click()
  await expect(page.locator('.sequence-event')).toHaveCount(state.events.filter((e: any) => (e.kind === 'SEND' && ['/prepare', '/decision'].includes(e.data.path)) || ['VOTE', 'DURABLE_DECISION', 'PROCESS_CRASH', 'COORDINATOR_RECOVERY'].includes(e.kind)).length)
  await close(page)
  await page.getByRole('button', { name: /^Trình chiếu/ }).click()
  await expect(page.locator('.app')).toHaveClass(/presentation/)
  await page.screenshot({ path: '../test-results/reference-2pc-presentation.png', fullPage: true })
  await page.getByRole('button', { name: 'Khởi động & phục hồi' }).click()
  await expect.poll(async () => (await (await request.get('/api/state')).json()).run.status, { timeout: 20000 }).toBe('COMPLETED')
  await expect(page.locator('.topology-page:not([hidden]) .service-node.server-node .node-status')).toHaveText(['COMMIT', 'COMMIT', 'COMMIT'])
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: /^Trình chiếu/ })).toBeVisible()
})

test('native inspector traps focus, restores it and honors reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.goto('/rpc')
  const trigger = page.getByRole('button', { name: 'Cài đặt', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(page.getByRole('button', { name: 'Đóng', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page.locator('.message-pulse')).toBeHidden()
})
