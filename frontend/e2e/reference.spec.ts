import { expect, test } from '@playwright/test'
test.beforeEach(async ({ request }) => { expect((await request.post('/api/reset')).ok()).toBeTruthy() })

test('reference layout makes scenario, run, topology and result visible in one desktop view', async ({ page, request }) => {
  await page.setViewportSize({ width: 1672, height: 940 })
  await page.goto('/rpc')
  await expect(page.getByTestId('connection')).toHaveAttribute('data-connected', 'true')
  await expect(page.locator('.stat-card')).toHaveCount(4)
  await expect(page.locator('.control-panel select')).toHaveCount(1)
  await expect(page.locator('.control-panel input[type="range"]')).toHaveCount(0)
  expect(await page.locator('h1').evaluate(element => parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(36)
  const sidebar = await page.locator('.sidebar').boundingBox(), canvas = await page.locator('.topology-panel').boundingBox(), controls = await page.locator('.control-panel').boundingBox()
  expect(sidebar!.x + sidebar!.width).toBeLessThan(canvas!.x)
  expect(canvas!.x + canvas!.width).toBeLessThan(controls!.x)
  expect(canvas!.width).toBeGreaterThan(controls!.width * 1.7)
  await expect(page.locator('.message-pulse')).toHaveCount(0)
  await expect(page.locator('.message-label')).toContainText(['Yêu cầu', 'Chờ phản hồi'])
  await page.getByRole('button', { name: 'Chạy thí nghiệm', exact: true }).click()
  await expect(page.getByTestId('current-status')).toContainText('Hoàn thành thành công')
  const state = await (await request.get('/api/state')).json()
  await expect(page.getByTestId('metric-Yêu cầu')).toHaveText(String(state.events.filter((event: any) => event.kind === 'SEND' && event.data.path === '/rpc').length))
  await expect(page.getByTestId('rpc-executions')).toContainText(String(state.nodes.A.counters.rpc))
  expect(await page.locator('.timeline-step').count()).toBeLessThanOrEqual(3)
  const status = await page.getByTestId('current-status').boundingBox()
  expect(status!.y + status!.height).toBeLessThan(940)
  await page.screenshot({ path: '../test-results/reference-final-rpc-1672.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../test-results/reference-final-rpc-1440.png', fullPage: true })
})

test('fault switches select real scenarios and reset clears real state', async ({ page, request }) => {
  await page.goto('/rpc')
  await expect(page.getByTestId('connection')).toHaveAttribute('data-connected', 'true')
  await page.getByRole('switch', { name: 'Mất yêu cầu', exact: true }).check()
  await expect(page.locator('#scenario')).toHaveValue('lost_request')
  await page.getByRole('switch', { name: 'Mất phản hồi', exact: true }).check()
  await expect(page.getByRole('switch', { name: 'Mất yêu cầu', exact: true })).not.toBeChecked()
  await expect(page.locator('#scenario')).toHaveValue('lost_response')
  await page.getByRole('button', { name: '2×', exact: true }).click()
  await page.getByRole('button', { name: 'Chạy thí nghiệm', exact: true }).click()
  await expect(page.getByTestId('current-status')).toContainText('Hoàn thành thành công')
  const state = await (await request.get('/api/state')).json()
  expect(state.run.config.scenario).toBe('lost_response')
  expect(state.run.config.pace_ms).toBe(300)
  expect(state.events.some((event: any) => event.kind === 'RESPONSE_LOST')).toBe(true)
  expect(state.events.some((event: any) => event.kind === 'RETRY')).toBe(true)
  expect(state.nodes.A.counters.rpc).toBe(1)
  await page.getByRole('button', { name: 'Đặt lại', exact: true }).click()
  await expect(page.getByTestId('current-status')).toContainText('Sẵn sàng chạy')
  const reset = await (await request.get('/api/state')).json()
  expect(reset.run).toBeNull()
  expect(reset.nodes.A.counters.rpc).toBe(0)
  await expect(page.locator('.timeline-empty')).toBeVisible()
})
